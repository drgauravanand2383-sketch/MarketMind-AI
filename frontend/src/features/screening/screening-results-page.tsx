import type { ReactNode } from "react";
import { Link } from "@tanstack/react-router";
import { EmptyState } from "@/components/states/empty-state";
import { ErrorState } from "@/components/states/error-state";
import { SkeletonList } from "@/components/states/skeleton";
import { ScreeningResultsTable } from "@/features/screening/screening-results-table";
import { useScreeningProfile, useScreeningResult } from "@/hooks/use-screening";
import { ApiError } from "@/services/api/errors";
import { useComparisonStore } from "@/store/comparison-store";

export function ScreeningResultsPage({ resultId }: { resultId: string }): ReactNode {
  const result = useScreeningResult(resultId);
  const compareIds = useComparisonStore((state) => state.screeningResultIds);
  const toggleCompare = useComparisonStore((state) => state.toggleScreeningResult);
  const isSelectedForCompare = compareIds.includes(resultId);

  // Only fetched once the result itself has resolved, so we have a real
  // `profile_id` to look up — the profile's own name is shown purely for
  // context and degrades gracefully (falls back to the raw id) if it was
  // since deleted.
  const profile = useScreeningProfile(result.data?.profile_id ?? "");

  if (result.isPending) {
    return (
      <div className="p-6">
        <SkeletonList rows={6} rowClassName="h-10 w-full" />
      </div>
    );
  }

  if (result.isError) {
    const isNotFound = result.error instanceof ApiError && result.error.status === 404;
    if (isNotFound) {
      return (
        <div className="p-6">
          <EmptyState
            icon="🧮"
            title="Result no longer available"
            description="This screening run was generated by a backend process that has since restarted — results aren't stored durably. Run the screen again for a fresh result."
          />
        </div>
      );
    }
    return (
      <div className="p-6">
        <ErrorState
          title="Couldn't load this screening result"
          message={result.error.message}
          onRetry={() => {
            void result.refetch();
          }}
        />
      </div>
    );
  }

  const envelope = result.data;

  return (
    <div className="flex flex-col gap-6 p-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-lg font-semibold text-slate-900 dark:text-slate-100">
            {profile.data ? (
              <Link to="/screening/$profileId" params={{ profileId: envelope.profile_id }} className="hover:underline">
                {profile.data.name}
              </Link>
            ) : (
              "Screening result"
            )}
          </h1>
          <p className="mt-1 text-xs text-slate-500 dark:text-slate-400">Result ID {resultId}</p>
        </div>
        <button
          type="button"
          aria-pressed={isSelectedForCompare}
          onClick={() => {
            toggleCompare(resultId);
          }}
          className={
            isSelectedForCompare
              ? "rounded-md bg-brand-600 px-3 py-2 text-sm font-medium text-white hover:bg-brand-700"
              : "rounded-md border border-slate-300 px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-100 dark:border-slate-700 dark:text-slate-300 dark:hover:bg-slate-800"
          }
        >
          {isSelectedForCompare ? "Selected for comparison" : "Add to comparison"}
        </button>
        {compareIds.length >= 2 && (
          <Link
            to="/screening/compare"
            className="rounded-md border border-slate-300 px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-100 dark:border-slate-700 dark:text-slate-300 dark:hover:bg-slate-800"
          >
            Compare selected ({compareIds.length})
          </Link>
        )}
      </div>

      {envelope.results.length === 0 ? (
        <EmptyState title="No companies were screened" description="This run didn't include any companies." />
      ) : (
        <ScreeningResultsTable results={envelope.results} />
      )}
    </div>
  );
}
