import type { ReactNode } from "react";
import { Link } from "@tanstack/react-router";
import { Panel } from "@/components/panel";
import { EmptyState } from "@/components/states/empty-state";
import { ErrorState } from "@/components/states/error-state";
import { SkeletonList } from "@/components/states/skeleton";
import { WeightedBarList } from "@/components/weighted-bar-list";
import {
  KeyRisksList,
  LatestNewsList,
  RelationshipList,
  SupportingEvidenceList,
} from "@/features/research/research-evidence-panel";
import { ResearchNarrativePanel } from "@/features/research/research-narrative-panel";
import { ResearchSummaryCards } from "@/features/research/research-summary-cards";
import { useResearchReport } from "@/hooks/use-research";
import { ApiError } from "@/services/api/errors";
import { useComparisonStore } from "@/store/comparison-store";

export function ResearchResultPage({ requestId }: { requestId: string }): ReactNode {
  const report = useResearchReport(requestId);
  const compareIds = useComparisonStore((state) => state.researchRequestIds);
  const toggleCompare = useComparisonStore((state) => state.toggleResearch);
  const isSelectedForCompare = compareIds.includes(requestId);

  if (report.isPending) {
    return (
      <div className="p-6">
        <SkeletonList rows={6} rowClassName="h-10 w-full" />
      </div>
    );
  }

  if (report.isError) {
    const isNotFound = report.error instanceof ApiError && report.error.status === 404;
    if (isNotFound) {
      return (
        <div className="p-6">
          <EmptyState
            icon="🔍"
            title="Report no longer available"
            description="This research report was generated by a backend process that has since restarted — reports aren't stored durably. Run the research again to get a fresh report."
          />
        </div>
      );
    }
    return (
      <div className="p-6">
        <ErrorState
          title="Couldn't load this research report"
          message={report.error.message}
          onRetry={() => {
            void report.refetch();
          }}
        />
      </div>
    );
  }

  const { report: data } = report.data;
  const overview = data.company_overview;

  return (
    <div className="flex flex-col gap-6 p-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-lg font-semibold text-slate-900 dark:text-slate-100">
            {overview.company_name}
            {overview.ticker && <span className="ml-2 text-sm font-normal text-slate-500 dark:text-slate-400">{overview.ticker}</span>}
          </h1>
          <p className="mt-1 text-xs text-slate-500 dark:text-slate-400">
            Generated {new Date(data.generated_at).toLocaleString()} · Request ID {requestId}
          </p>
        </div>
        <div className="flex gap-2">
          <button
            type="button"
            aria-pressed={isSelectedForCompare}
            onClick={() => {
              toggleCompare(requestId);
            }}
            className={
              isSelectedForCompare
                ? "rounded-md bg-brand-600 px-3 py-2 text-sm font-medium text-white hover:bg-brand-700"
                : "rounded-md border border-slate-300 px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-100 dark:border-slate-700 dark:text-slate-300 dark:hover:bg-slate-800"
            }
          >
            {isSelectedForCompare ? "Selected for comparison" : "Add to comparison"}
          </button>
          {compareIds.length >= 2 && (
            <Link
              to="/research/compare"
              className="rounded-md border border-slate-300 px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-100 dark:border-slate-700 dark:text-slate-300 dark:hover:bg-slate-800"
            >
              Compare selected ({compareIds.length})
            </Link>
          )}
          <button
            type="button"
            disabled
            title="Export isn't implemented yet"
            className="rounded-md border border-slate-300 px-3 py-2 text-sm font-medium text-slate-400 dark:border-slate-700 dark:text-slate-600"
          >
            Export (coming soon)
          </button>
        </div>
      </div>

      <ResearchSummaryCards report={data} />

      <div className="grid grid-cols-1 gap-4 lg:grid-cols-3">
        <Panel title="Sector exposure">
          <WeightedBarList title="" items={data.sector_analysis.map((s) => ({ label: s.sector, weight: s.weight }))} emptyMessage="No sector exposure data." />
        </Panel>
        <Panel title="Country exposure">
          <WeightedBarList title="" items={data.country_exposure.map((c) => ({ label: c.country, weight: c.weight }))} emptyMessage="No country exposure data." />
        </Panel>
        <Panel title="Recurring themes">
          <WeightedBarList
            title=""
            items={data.theme_analysis.map((t) => ({ label: t.keyword, weight: t.occurrence_count }))}
            emptyMessage="No recurring themes found."
          />
        </Panel>
      </div>

      <Panel title="Narrative">
        <ResearchNarrativePanel narrative={data.narrative} />
      </Panel>

      <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        <Panel title="Latest news">
          <LatestNewsList items={data.latest_news} />
        </Panel>
        <Panel title="Supporting evidence">
          <SupportingEvidenceList items={data.supporting_evidence} />
        </Panel>
      </div>

      <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        <Panel title="Relationships">
          <RelationshipList items={data.relationship_analysis} />
        </Panel>
        <Panel title="Data quality notes">
          <KeyRisksList items={data.key_risks} />
        </Panel>
      </div>
    </div>
  );
}
